import Link from "next/link";
import { AlertTriangle } from "lucide-react";
import { getDashboardData } from "@/server/services/analytics-service";
import { getSettings } from "@/server/services/settings-service";
import { demoCollector } from "@/server/collectors/demo/demo-collector";
import { Card, CardTitle, PageHeader } from "@/components/ui/card";
import { StatCard } from "@/components/ui/stat-card";
import { Badge, HealthBadge, ProvenanceBadge } from "@/components/ui/badge";
import { EmptyState } from "@/components/ui/empty-state";
import { RunCollectorButton } from "@/components/collectors/run-collector-button";
import { UsageTrendChart } from "@/components/charts/usage-trend-chart";
import { CostByProviderChart } from "@/components/charts/cost-by-provider-chart";
import {
  formatCompact,
  formatCurrency,
  formatDateTime,
  formatPercent,
  formatTokens,
} from "@/lib/format";

export default async function OverviewPage() {
  const [data, settings] = await Promise.all([getDashboardData(), getSettings()]);
  const currency = settings.displayCurrency;

  return (
    <>
      <PageHeader
        title="Overview"
        description="Month-to-date picture of AI spend, usage, and collector health."
        action={<RunCollectorButton collectorId={demoCollector.id} />}
      />

      <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        <StatCard
          label="Est. monthly cost"
          value={formatCurrency(data.monthTotals.total, currency)}
          trend={
            <p className="mt-1 text-xs text-muted-foreground">
              {data.costChangePercent === null
                ? "vs previous month: unknown"
                : `${formatPercent(data.costChangePercent)} vs previous month`}
            </p>
          }
          hint="Demo estimates + demo subscription fees"
        />
        <StatCard
          label="Active connections"
          value={`${data.activeConnectionCount} / ${data.totalConnectionCount}`}
          badge={<Badge tone="muted">local</Badge>}
          hint="Connections with local, demo, or manual tracking"
        />
        <StatCard
          label="Usage events today"
          value={data.eventsToday}
          hint="Generated by the demo collector"
        />
        {data.realClaudeUsage.eventCount > 0 && (
          <StatCard
            label="Claude Code tokens (real)"
            value={formatCompact(data.realClaudeUsage.totalTokens)}
            badge={<ProvenanceBadge provenance="locally-observed" />}
            trend={
              <p className="mt-1 text-xs text-muted-foreground">
                {formatTokens(data.realClaudeUsage.eventCount)} imported events —{" "}
                <Link href="/providers/claude-code" className="text-accent hover:underline">
                  details
                </Link>
              </p>
            }
            hint="Imported locally; kept separate from demo totals"
          />
        )}
        <StatCard
          label="Collector health"
          value={
            data.lastRun ? (
              <HealthBadge status={data.lastRun.status === "success" ? "ok" : "down"} />
            ) : (
              <HealthBadge status="unknown" />
            )
          }
          badge={<Badge tone="muted">local</Badge>}
          hint={
            data.lastRun
              ? `Last run ${formatDateTime(data.lastRun.startedAt)}`
              : "No collector has run yet"
          }
        />
      </div>

      <div className="mt-4 grid gap-4 lg:grid-cols-2">
        <Card>
          <CardTitle action={<Badge tone="demo">demo</Badge>}>
            Usage trend — last 14 days
          </CardTitle>
          <UsageTrendChart data={data.usageTrend} />
        </Card>
        <Card>
          <CardTitle action={<Badge tone="demo">demo</Badge>}>
            Cost by provider — this month
          </CardTitle>
          {data.costByProvider.length > 0 ? (
            <CostByProviderChart data={data.costByProvider} currency={currency} />
          ) : (
            <EmptyState
              title="No cost data this month"
              description="Run the demo collector or add manual records to see the breakdown."
            />
          )}
        </Card>
      </div>

      <div className="mt-4 grid gap-4 lg:grid-cols-3">
        <Card className="lg:col-span-2">
          <CardTitle
            action={
              <Link
                href="/activity"
                className="text-xs text-accent hover:underline"
              >
                View all
              </Link>
            }
          >
            Recent activity
          </CardTitle>
          {data.recentEvents.length > 0 ? (
            <div className="overflow-x-auto">
              <table className="w-full text-sm">
                <caption className="sr-only">
                  Eight most recent usage events with provenance labels.
                </caption>
                <thead>
                  <tr className="border-b border-border text-left text-xs uppercase tracking-wide text-muted-foreground">
                    <th scope="col" className="py-2 pr-3 font-medium">Time</th>
                    <th scope="col" className="py-2 pr-3 font-medium">Connection</th>
                    <th scope="col" className="py-2 pr-3 font-medium">Model</th>
                    <th scope="col" className="py-2 pr-3 text-right font-medium">Tokens</th>
                    <th scope="col" className="py-2 font-medium">Source</th>
                  </tr>
                </thead>
                <tbody>
                  {data.recentEvents.map((e) => (
                    <tr key={e.id} className="border-b border-border/50">
                      <td className="tabular py-2 pr-3 whitespace-nowrap text-muted-foreground">
                        {formatDateTime(e.occurredAt)}
                      </td>
                      <td className="py-2 pr-3">{e.connection.name}</td>
                      <td className="py-2 pr-3 font-mono text-xs">
                        {e.model ?? <span className="text-faint-foreground">unknown</span>}
                      </td>
                      <td className="tabular py-2 pr-3 text-right font-mono text-xs">
                        {formatTokens(e.totalTokens)}
                      </td>
                      <td className="py-2">
                        <ProvenanceBadge provenance={e.provenance} />
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          ) : (
            <EmptyState
              title="No activity yet"
              description="Run the demo collector to generate clearly-labeled demo events."
            />
          )}
        </Card>

        <Card>
          <CardTitle>Data quality</CardTitle>
          <div className="flex items-start gap-3 text-sm text-muted-foreground">
            <AlertTriangle size={16} className="mt-0.5 shrink-0 text-demo" aria-hidden="true" />
            <div className="space-y-2">
              <p>
                AI cost values and the demo-labeled tiles on this dashboard are{" "}
                <span className="font-medium text-demo">demo data</span> generated
                locally. No real provider account has been read.
              </p>
              {data.realClaudeUsage.eventCount > 0 ? (
                <p>
                  Real data on this page: Claude Code usage imported from this
                  machine, always labeled{" "}
                  <ProvenanceBadge provenance="locally-observed" /> and never
                  mixed into demo totals.
                </p>
              ) : (
                <p>
                  Real Claude Code usage can be imported from this machine on
                  the Claude Code connection page; until then, no real AI usage
                  is shown.
                </p>
              )}
              <p>
                Subscription fees are demo placeholders marked{" "}
                <ProvenanceBadge provenance="demo" /> until you track them manually.
              </p>
              <p>
                ChatGPT and Claude subscription quotas are{" "}
                <span className="font-medium">not available</span> through any
                supported interface, so they are never shown.
              </p>
            </div>
          </div>
        </Card>
      </div>
    </>
  );
}
